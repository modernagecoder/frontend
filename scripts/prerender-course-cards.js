#!/usr/bin/env node
/**
 * prerender-course-cards.js
 * ------------------------------------------------------------------
 * Puts the course catalogue into the HTML of /courses.
 *
 * The page rendered every card with JavaScript from the coursesData
 * array, so without scripts the grid was an empty <div>, the markdown
 * twin for AI agents carried no courses, and the only crawlable course
 * links were a hand-typed "Browse All" strip that listed 72 of the 129
 * entries and drifted every time a course was added.
 *
 * This script writes, from the same coursesData array and the same
 * generateCourseCard() function the page itself uses:
 *   1. the default view's cards (coding, kids) as static HTML inside
 *      #coursesGrid, byte-identical to what the JS renders on load so
 *      there is no flash, and
 *   2. the "Browse all N courses" index: every course, grouped by
 *      audience, as a plain list of real links.
 *
 * Both live between markers so the run is idempotent. Runs inside
 * generate:html on every build and can be run by hand:
 *
 *   node scripts/prerender-course-cards.js          # write
 *   node scripts/prerender-course-cards.js --check  # exit 1 if stale
 */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.join(__dirname, '..');
const FILE = path.join(ROOT, 'src/pages/course.html');
const CHECK = process.argv.includes('--check');

const CARDS_START = '<!-- BEGIN_STATIC_CARDS: generated by scripts/prerender-course-cards.js, do not edit -->';
const CARDS_END = '<!-- END_STATIC_CARDS -->';
const INDEX_START = '<!-- BEGIN_COURSE_INDEX: generated by scripts/prerender-course-cards.js, do not edit -->';
const INDEX_END = '<!-- END_COURSE_INDEX -->';

const CODING = ['programming', 'web-dev', 'mobile-dev', 'ai-ml', 'design', 'finance', 'productivity', 'logic', 'coding', 'technology', 'game-dev', 'cyber-security', 'backend-dev', 'app-dev'];

// Audience groups for the index, in display order. A course appears once, in
// the first group that claims it, so the four Olympiad entries (one per level)
// link the same page once.
const GROUPS = [
  { title: 'Coding for kids (ages 6 to 12)', pick: (c) => CODING.includes(c.category) && c.ageGroup === 'kids' },
  { title: 'Coding for teens (ages 13 to 18)', pick: (c) => CODING.includes(c.category) && c.ageGroup === 'teens' },
  { title: 'Coding for college students', pick: (c) => CODING.includes(c.category) && c.ageGroup === 'college' },
  { title: 'Coding for working professionals', pick: (c) => CODING.includes(c.category) && c.ageGroup === 'professional' },
  { title: 'Maths for elementary school', pick: (c) => c.category === 'mathematics' && c.ageGroup === 'elementary' },
  { title: 'Maths for middle school', pick: (c) => c.category === 'mathematics' && c.ageGroup === 'middle' },
  { title: 'Maths for high school and board exams', pick: (c) => c.category === 'mathematics' && (c.ageGroup === 'high' || c.ageGroup === 'teens') },
  { title: 'Maths for college and professionals', pick: (c) => c.category === 'mathematics' && (c.ageGroup === 'college' || c.ageGroup === 'professional') },
  { title: 'Special batches for girls', pick: (c) => c.ageGroup === 'girls' },
];

function esc(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

function extract(html) {
  const s = html.indexOf('const coursesData = [');
  const e = html.indexOf('];', s);
  if (s < 0 || e < 0) throw new Error('coursesData not found');
  const data = vm.runInNewContext('(' + html.slice(s + 'const coursesData = '.length, e + 1) + ')');
  const fs_ = html.indexOf('function generateCourseCard(course) {');
  const fe = html.indexOf('function initializeCardClicks() {', fs_);
  if (fs_ < 0 || fe < 0) throw new Error('generateCourseCard not found');
  const fnSrc = html.slice(fs_, fe);
  return { data, fnSrc };
}

function renderCards(fnSrc, list) {
  // Same function, same inputs as the browser: Indian pricing is the static
  // default (the page re-prices for other regions at runtime).
  const ctx = { window: { __MAC_IS_INDIAN: true }, list, out: '' };
  vm.runInNewContext(fnSrc + '\nout = list.map(generateCourseCard).join("");', ctx);
  return ctx.out;
}

function listHtml(items) {
  return items.map((c) => '                <li><a href="' + esc(c.templateUrl) + '">' + esc(c.title) + '</a></li>').join('\n');
}

function renderIndex(data) {
  const seen = new Set();
  const parts = [];
  let total = 0;
  for (const g of GROUPS) {
    const items = data.filter((c) => g.pick(c) && c.templateUrl && !seen.has(c.templateUrl));
    if (!items.length) continue;
    items.forEach((c) => seen.add(c.templateUrl));
    total += items.length;
    parts.push('            <h3>' + esc(g.title) + '</h3>\n            <ul class="bas-list">\n' + listHtml(items) + '\n            </ul>');
  }
  const left = data.filter((c) => c.templateUrl && !seen.has(c.templateUrl));
  if (left.length) {
    total += left.length;
    parts.push('            <h3>More courses</h3>\n            <ul class="bas-list">\n' + listHtml(left) + '\n            </ul>');
  }
  const head = '            <h2>Browse all ' + total + ' courses</h2>\n' +
    '            <p class="bas-sub">Every live course we teach, by audience. Each link opens the full syllabus, projects, schedule and pricing.</p>\n';
  return { total, html: head + parts.join('\n') };
}

function between(html, start, end, inner) {
  const s = html.indexOf(start);
  const e = html.indexOf(end);
  if (s < 0 || e < 0 || e < s) return null;
  // keep the indentation in front of the end marker, so a rewrite is byte-identical
  const lineStart = html.lastIndexOf('\n', e) + 1;
  return html.slice(0, s + start.length) + '\n' + inner + '\n' + html.slice(lineStart);
}

function main() {
  const original = fs.readFileSync(FILE, 'utf8');
  let html = original;
  const { data, fnSrc } = extract(html);

  // 1. default cards
  const defaults = data.filter((c) => CODING.includes(c.category) && c.ageGroup === 'kids');
  const cards = renderCards(fnSrc, defaults).trim();
  if (html.includes(CARDS_START)) {
    html = between(html, CARDS_START, CARDS_END, cards);
  } else {
    const placeholder = '<!-- Course Cards will be generated by JavaScript -->';
    if (!html.includes(placeholder)) throw new Error('grid placeholder not found');
    html = html.replace(placeholder, CARDS_START + '\n' + cards + '\n' + CARDS_END);
  }
  html = html.replace(/(Showing <strong id="resultsCount">)\d+(<\/strong> courses)/, '$1' + defaults.length + '$2');

  // 2. the index
  const index = renderIndex(data);
  if (html.includes(INDEX_START)) {
    html = between(html, INDEX_START, INDEX_END, index.html);
  } else {
    const secStart = html.indexOf('<section class="browse-all-seo">');
    const secEnd = html.indexOf('</section>', secStart);
    if (secStart < 0 || secEnd < 0) throw new Error('browse-all-seo section not found');
    html = html.slice(0, secStart) +
      '<section class="browse-all-seo" id="all-courses">\n            ' + INDEX_START + '\n' + index.html + '\n            ' + INDEX_END + '\n        ' +
      html.slice(secEnd);
  }

  const changed = html !== original;
  if (CHECK) {
    if (changed) { console.error('course.html is stale: run node scripts/prerender-course-cards.js'); process.exit(1); }
    console.log('course.html static cards and index are current.');
    return;
  }
  if (changed) fs.writeFileSync(FILE, html);
  console.log('course.html: ' + defaults.length + ' default cards in HTML, ' + index.total + ' courses in the index' + (changed ? '' : ' (unchanged)'));
}

main();
